[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)
# N1 家里安装：飞书笔记副本装进 feishu-tutor-tool，试跑一次，再注册每 30 分钟一次的计划任务。
# 脚本轮 mode=write：用户在评论上点 👍 后由 watcher 运行。只读飞书，不碰 lark-cli 配置和登录。
# 先核对同目录 n1-install.mjs 的 SHA256 再用 PATH 里的 node.exe 运行；mjs 退出 0 才注册任务。
# 输出每行一个 JSON，不含令牌、本机路径、SID 或文档内容。
$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSEdition -ne 'Desktop' -or $PSVersionTable.PSVersion.Major -ne 5) { throw 'host_not_51' }
$env:PSModulePath = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\Modules'
foreach ($name in @(Get-ChildItem Env: | Where-Object { $_.Name -like 'NODE_*' -or $_.Name -like 'FEISHU_TUTOR_*' -or $_.Name -like 'I_CORE_*' -or $_.Name -like 'I_REMOTE_MCP_*' -or $_.Name -like 'GIT_*' } | ForEach-Object { $_.Name })) {
  Remove-Item -LiteralPath ('Env:' + $name)
}
$mjs = Join-Path $PSScriptRoot 'n1-install.mjs'
$sha = [Security.Cryptography.SHA256]::Create()
# core.autocrlf=true 检出会把 LF 变成 CRLF：原字节或把 CRLF 还原成 LF 后的字节，任一与提交版一致即可。
$bytes = [IO.File]::ReadAllBytes($mjs)
$lf = [Text.Encoding]::UTF8.GetBytes([Text.Encoding]::UTF8.GetString($bytes).Replace("`r`n", "`n"))
try { $actual = @(foreach ($b in @($bytes, $lf)) { ([BitConverter]::ToString($sha.ComputeHash($b))).Replace('-', '').ToLowerInvariant() }) } finally { $sha.Dispose() }
if ($actual -notcontains 'aefca6f86b2d0394079cb1ff168eadbe4eac50b5a0bd69c0525d5cc12def0b5b') { Write-Output '{"step":"launcher","ok":false,"detail":"mjs_hash_mismatch"}'; exit 1 }
$node = @(Get-Command node.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1)
if ($node.Count -ne 1) { Write-Output '{"step":"launcher","ok":false,"detail":"node_not_found"}'; exit 1 }
$nodePath = $node[0].Source
Write-Output '{"step":"launcher","ok":true,"detail":"mjs_hash_ok"}'

& $nodePath $mjs
$installExit = $LASTEXITCODE
if ($installExit -ne 0) {
  Write-Output ('{"step":"schedule","ok":false,"detail":"skipped_install_exit_' + $installExit + '"}')
  exit 1
}

# 计划任务：Interactive（只在用户登录时运行，lark-cli 的设备绑定需要登录用户），
# wscript 隐藏窗口启动 cmd，输出追加到工具目录 logs\notes-mirror.log。
try {
  $taskName = 'FeishuNotes-Mirror'
  $tool = Join-Path $env:USERPROFILE 'feishu-tutor-tool'
  $logs = Join-Path $tool 'logs'
  New-Item -ItemType Directory -Path $logs -Force | Out-Null
  $vbs = Join-Path $tool 'notes-mirror.vbs'
  $mirror = Join-Path $tool 'sync\notes_mirror.mjs'
  $config = Join-Path $tool 'config.json'
  $state = Join-Path $env:USERPROFILE 'feishu-study\state'
  $notes = Join-Path $env:USERPROFILE 'feishu-notes'
  $log = Join-Path $logs 'notes-mirror.log'
  foreach ($p in @($nodePath, $mirror, $config, $state, $notes, $log)) { if ($p.Contains('"') -or $p.Contains('%')) { throw 'path_unsupported_character' } }
  $q = '"'
  $inner = $q + $nodePath + $q + ' ' + $q + $mirror + $q + ' --config ' + $q + $config + $q + ' --state ' + $q + $state + $q + ' --notes ' + $q + $notes + $q + ' >> ' + $q + $log + $q + ' 2>&1'
  $cmdLine = 'cmd.exe /d /s /c ' + $q + $inner + $q
  $vbsText = "' FeishuNotes-Mirror launcher (generated by n1-install). Hidden window, waits, passes the exit code on.`r`n" +
    'WScript.Quit CreateObject("WScript.Shell").Run("' + $cmdLine.Replace('"', '""') + '", 0, True)' + "`r`n"
  [IO.File]::WriteAllText($vbs, $vbsText, [Text.Encoding]::Unicode)

  $wscript = Join-Path $env:SystemRoot 'System32\wscript.exe'
  $existing = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
  if ($existing) {
    $a = $existing.Actions[0]
    if ($a.Execute -ne $wscript -or -not ([string]$a.Arguments).Contains($vbs)) { throw 'task_name_taken' }
  }
  $now = Get-Date
  $start = $now.Date.AddHours($now.Hour).AddMinutes(10)
  while ($start -lt $now.AddMinutes(2)) { $start = $start.AddMinutes(30) }
  $action = New-ScheduledTaskAction -Execute $wscript -Argument ('//B //NoLogo "' + $vbs + '"')
  $trigger = New-ScheduledTaskTrigger -Once -At $start -RepetitionInterval (New-TimeSpan -Minutes 30)
  $user = [Security.Principal.WindowsIdentity]::GetCurrent().Name
  $principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
  $settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 25) -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
  Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Description 'Read-only Feishu notes mirror for the i MCP (every 30 minutes).' -Force | Out-Null
  # 重复无期限：有的系统默认给 Once 触发器一个有限时长，这里清空。
  $task = Get-ScheduledTask -TaskName $taskName
  if ($task.Triggers[0].Repetition.Duration) {
    $task.Triggers[0].Repetition.Duration = ''
    Set-ScheduledTask -InputObject $task | Out-Null
    $task = Get-ScheduledTask -TaskName $taskName
  }
  $rep = $task.Triggers[0].Repetition
  $info = Get-ScheduledTaskInfo -TaskName $taskName
  $detail = 'state=' + [string]$task.State + ' logon=' + [string]$task.Principal.LogonType + ' interval=' + [string]$rep.Interval + ' duration=' + $(if ($rep.Duration) { [string]$rep.Duration } else { 'indefinite' }) + ' next=' + $(if ($info.NextRunTime) { $info.NextRunTime.ToString('yyyy-MM-ddTHH:mm') } else { 'none' }) + ' replaced=' + [string][bool]$existing
  Write-Output (ConvertTo-Json -Compress -InputObject ([ordered]@{ step = 'schedule'; ok = $true; detail = $detail }))
  exit 0
} catch {
  $msg = [string]$_.Exception.Message
  if ($msg -notmatch '^[a-z_]{1,60}$') { $msg = 'register_failed:' + $_.Exception.GetType().Name }
  Write-Output (ConvertTo-Json -Compress -InputObject ([ordered]@{ step = 'schedule'; ok = $false; detail = $msg }))
  exit 1
}
